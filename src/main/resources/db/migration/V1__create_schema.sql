create table project (
  id          bigint generated by default as identity primary key,
  slug        varchar(100) not null unique,
  status      varchar(20)  not null check (status in ('CURRENT', 'PAST')),
  started_on  date,
  ended_on    date,
  repo_url    varchar(500),
  demo_url    varchar(500),
  sort_order  int          not null,
  published   boolean      not null default false,
  constraint project_slug_format check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint project_dates check (ended_on is null or started_on is null or ended_on >= started_on)
);

create table project_translation (
  id          bigint generated by default as identity primary key,
  project_id  bigint       not null references project (id) on delete cascade,
  locale      varchar(5)   not null check (locale in ('en', 'de')),
  title       varchar(200) not null,
  summary     varchar(500) not null,
  description text         not null,
  constraint project_translation_project_locale unique (project_id, locale)
);

create table project_image (
  id          bigint generated by default as identity primary key,
  project_id  bigint       not null references project (id) on delete cascade,
  path        varchar(300) not null,
  alt_en      varchar(300),
  alt_de      varchar(300),
  sort_order  int          not null
);

create index project_image_project_id on project_image (project_id);

create table technology (
  id    bigint generated by default as identity primary key,
  name  varchar(100) not null unique
);

create table project_technology (
  project_id     bigint not null references project (id) on delete cascade,
  technology_id  bigint not null references technology (id),
  primary key (project_id, technology_id)
);

create index project_technology_technology_id on project_technology (technology_id);

create table certification (
  id              bigint generated by default as identity primary key,
  name            varchar(200) not null,
  issuer          varchar(200) not null,
  issued_on       date,
  credential_url  varchar(500),
  sort_order      int          not null
);

create table contact_message (
  id          bigint generated by default as identity primary key,
  name        varchar(100)  not null,
  email       varchar(254)  not null,
  message     text          not null,
  created_at  timestamptz   not null default now(),
  mail_sent   boolean       not null default false
);
